import {
  idParamsSchema,
  paginatedSchema,
  paginationQuerySchema,
} from '../common';
import {
  customerBodySchema,
  customerSchema,
  listCustomersQuerySchema,
} from '../customers';
import {
  createOrderBodySchema,
  listOrdersQuerySchema,
  orderSchema,
  updateOrderStatusBodySchema,
} from '../orders';
import {
  listProductsQuerySchema,
  productBodySchema,
  productSchema,
} from '../products';
import {
  avatarUploadBodySchema,
  createUserBodySchema,
  forgotPasswordBodySchema,
  resetPasswordBodySchema,
  sessionBodySchema,
  sessionSchema,
  updateProfileBodySchema,
  userSchema,
} from '../users';
import { defineRoute, RouteDefinition } from './define';

/**
 * Contrato único da API: a fonte para o roteamento e a validação da API,
 * para o openapi.json e, a partir dele, para o client tipado do front-end.
 */
export const routes = {
  users: {
    create: defineRoute({
      method: 'post',
      path: '/users',
      operationId: 'createUser',
      summary: 'Cadastra um usuário',
      tags: ['Usuários'],
      auth: false,
      rateLimited: true,
      request: { body: createUserBodySchema },
      responses: { 201: userSchema },
      errors: [409],
    }),
    list: defineRoute({
      method: 'get',
      path: '/users',
      operationId: 'listUsers',
      summary: 'Lista usuários',
      tags: ['Usuários'],
      auth: true,
      request: { query: paginationQuerySchema },
      responses: { 200: paginatedSchema(userSchema) },
    }),
    updateAvatar: defineRoute({
      method: 'patch',
      path: '/users/avatar',
      operationId: 'updateUserAvatar',
      summary: 'Envia o avatar (jpeg, png ou webp, até 2 MB)',
      tags: ['Usuários'],
      auth: true,
      request: { body: avatarUploadBodySchema, bodyType: 'multipart' },
      responses: { 200: userSchema },
    }),
  },

  sessions: {
    create: defineRoute({
      method: 'post',
      path: '/sessions',
      operationId: 'createSession',
      summary: 'Login: devolve o usuário e um JWT',
      tags: ['Autenticação'],
      auth: false,
      rateLimited: true,
      request: { body: sessionBodySchema },
      responses: { 200: sessionSchema },
      // credenciais inválidas
      errors: [401],
    }),
  },

  profile: {
    show: defineRoute({
      method: 'get',
      path: '/profile',
      operationId: 'showProfile',
      summary: 'Mostra o perfil do usuário autenticado',
      tags: ['Perfil'],
      auth: true,
      responses: { 200: userSchema },
      errors: [404],
    }),
    update: defineRoute({
      method: 'put',
      path: '/profile',
      operationId: 'updateProfile',
      summary: 'Atualiza o perfil (trocar a senha exige old_password)',
      tags: ['Perfil'],
      auth: true,
      request: { body: updateProfileBodySchema },
      responses: { 200: userSchema },
      errors: [404, 409],
    }),
  },

  password: {
    forgot: defineRoute({
      method: 'post',
      path: '/password/forgot',
      operationId: 'forgotPassword',
      summary: 'Envia o e-mail de recuperação',
      description:
        'Responde 204 mesmo se o e-mail não existir (não revela contas).',
      tags: ['Autenticação'],
      auth: false,
      rateLimited: true,
      request: { body: forgotPasswordBodySchema },
      responses: { 204: null },
    }),
    reset: defineRoute({
      method: 'post',
      path: '/password/reset',
      operationId: 'resetPassword',
      summary: 'Redefine a senha com o token recebido por e-mail',
      description: 'O token vale por 2 horas e só pode ser usado uma vez.',
      tags: ['Autenticação'],
      auth: false,
      rateLimited: true,
      request: { body: resetPasswordBodySchema },
      responses: { 204: null },
    }),
  },

  products: {
    list: defineRoute({
      method: 'get',
      path: '/products',
      operationId: 'listProducts',
      summary: 'Lista produtos (público), com busca e ordenação',
      tags: ['Produtos'],
      auth: false,
      request: { query: listProductsQuerySchema },
      responses: { 200: paginatedSchema(productSchema) },
    }),
    show: defineRoute({
      method: 'get',
      path: '/products/{id}',
      operationId: 'showProduct',
      summary: 'Mostra um produto (público)',
      tags: ['Produtos'],
      auth: false,
      request: { params: idParamsSchema },
      responses: { 200: productSchema },
      errors: [404],
    }),
    create: defineRoute({
      method: 'post',
      path: '/products',
      operationId: 'createProduct',
      summary: 'Cria um produto',
      tags: ['Produtos'],
      auth: true,
      request: { body: productBodySchema },
      responses: { 201: productSchema },
      errors: [409],
    }),
    update: defineRoute({
      method: 'put',
      path: '/products/{id}',
      operationId: 'updateProduct',
      summary: 'Atualiza um produto',
      tags: ['Produtos'],
      auth: true,
      request: { params: idParamsSchema, body: productBodySchema },
      responses: { 200: productSchema },
      errors: [404, 409],
    }),
    delete: defineRoute({
      method: 'delete',
      path: '/products/{id}',
      operationId: 'deleteProduct',
      summary: 'Remove um produto',
      description: '409 se houver pedidos com o produto.',
      tags: ['Produtos'],
      auth: true,
      request: { params: idParamsSchema },
      responses: { 204: null },
      errors: [404, 409],
    }),
  },

  customers: {
    list: defineRoute({
      method: 'get',
      path: '/customers',
      operationId: 'listCustomers',
      summary: 'Lista clientes, com busca e ordenação',
      tags: ['Clientes'],
      auth: true,
      request: { query: listCustomersQuerySchema },
      responses: { 200: paginatedSchema(customerSchema) },
    }),
    show: defineRoute({
      method: 'get',
      path: '/customers/{id}',
      operationId: 'showCustomer',
      summary: 'Mostra um cliente',
      tags: ['Clientes'],
      auth: true,
      request: { params: idParamsSchema },
      responses: { 200: customerSchema },
      errors: [404],
    }),
    create: defineRoute({
      method: 'post',
      path: '/customers',
      operationId: 'createCustomer',
      summary: 'Cria um cliente',
      tags: ['Clientes'],
      auth: true,
      request: { body: customerBodySchema },
      responses: { 201: customerSchema },
      errors: [409],
    }),
    update: defineRoute({
      method: 'put',
      path: '/customers/{id}',
      operationId: 'updateCustomer',
      summary: 'Atualiza um cliente',
      tags: ['Clientes'],
      auth: true,
      request: { params: idParamsSchema, body: customerBodySchema },
      responses: { 200: customerSchema },
      errors: [404, 409],
    }),
    delete: defineRoute({
      method: 'delete',
      path: '/customers/{id}',
      operationId: 'deleteCustomer',
      summary: 'Remove um cliente',
      description: '409 se houver pedidos do cliente.',
      tags: ['Clientes'],
      auth: true,
      request: { params: idParamsSchema },
      responses: { 204: null },
      errors: [404, 409],
    }),
  },

  orders: {
    list: defineRoute({
      method: 'get',
      path: '/orders',
      operationId: 'listOrders',
      summary: 'Lista pedidos (mais recentes primeiro)',
      tags: ['Pedidos'],
      auth: true,
      request: { query: listOrdersQuerySchema },
      responses: { 200: paginatedSchema(orderSchema) },
    }),
    show: defineRoute({
      method: 'get',
      path: '/orders/{id}',
      operationId: 'showOrder',
      summary: 'Mostra um pedido com os itens',
      tags: ['Pedidos'],
      auth: true,
      request: { params: idParamsSchema },
      responses: { 200: orderSchema },
      errors: [404],
    }),
    create: defineRoute({
      method: 'post',
      path: '/orders',
      operationId: 'createOrder',
      summary: 'Cria um pedido',
      description:
        'Em uma transação: trava os produtos, checa o estoque, copia o preço atual de cada produto, calcula o total e baixa o estoque. 409 se faltar estoque.',
      tags: ['Pedidos'],
      auth: true,
      request: { body: createOrderBodySchema },
      responses: { 201: orderSchema },
      errors: [404, 409],
    }),
    updateStatus: defineRoute({
      method: 'patch',
      path: '/orders/{id}/status',
      operationId: 'updateOrderStatus',
      summary: 'Conclui ou cancela um pedido pendente',
      description: 'Cancelar devolve os itens ao estoque.',
      tags: ['Pedidos'],
      auth: true,
      request: { params: idParamsSchema, body: updateOrderStatusBodySchema },
      responses: { 200: orderSchema },
      errors: [404, 409],
    }),
  },
} as const;

/** Todas as rotas, na ordem em que aparecem na documentação. */
export const allRoutes: readonly RouteDefinition[] = Object.values(
  routes,
).flatMap(group => Object.values<RouteDefinition>(group));
